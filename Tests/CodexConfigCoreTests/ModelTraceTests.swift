    func testMatchesUpstreamJavaScriptImplementation() throws {
        let bank = try bank
        for (name, outputs) in try referenceCases() {
            let expected = try XCTUnwrap(Self.jsReference[name])
            let result = try ModelTraceFingerprint.analyze(outputs, bank: bank)
            XCTAssertEqual(result.top.model, expected.prediction, name)
            XCTAssertEqual(result.usedOutputs, expected.used, name)
            XCTAssertEqual(result.beta, expected.beta, name)
            XCTAssertEqual(result.results.map(\.model), expected.results.map(\.0), name)
            for (actual, reference) in zip(result.results, expected.results) {
                XCTAssertEqual(actual.probability, reference.1, accuracy: 1e-9, "\(name) \(actual.model)")
                XCTAssertEqual(actual.profileSimilarity, reference.2, accuracy: 1e-9, "\(name) \(actual.model)")
                XCTAssertEqual(actual.score, reference.3, accuracy: 1e-9, "\(name) \(actual.model)")
                XCTAssertEqual(actual.conditionalProbability, reference.4, accuracy: 1e-9, "\(name) \(actual.model)")
            }
            XCTAssertEqual(result.families.map(\.family), expected.families.map(\.0), name)
            for (actual, reference) in zip(result.families, expected.families) {
                XCTAssertEqual(actual.probability, reference.1, accuracy: 1e-9, name)
            }
            XCTAssertEqual(result.diagnostics.map { [$0.parsedNumbers, $0.minimumNumbers, $0.accepted ? 1 : 0] },
                           expected.diagnostics.map { [$0.0, $0.1, $0.2 ? 1 : 0] }, name)
        }
    }

