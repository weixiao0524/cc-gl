private actor ScriptedTransport: DetectionTransport {
    enum Reply { case json(Int, String); case timeout }
    private let handler: @Sendable (URLRequest, Int) -> Reply
    private(set) var requests: [URLRequest] = []
    /// `handler` receives how many times this exact body was already sent (0 = first try).
    init(_ handler: @escaping @Sendable (URLRequest, Int) -> Reply) { self.handler = handler }
    func send(_ request: URLRequest) async throws -> (Data, HTTPURLResponse) {
        let repeats = requests.filter { $0.httpBody == request.httpBody }.count
        requests.append(request)
        switch handler(request, repeats) {
        case .timeout: throw URLError(.timedOut)
        case .json(let status, let body):
            return (Data(body.utf8), HTTPURLResponse(url: request.url!, statusCode: status, httpVersion: nil, headerFields: nil)!)
        }
    }
}

private struct SplitMix64: RandomNumberGenerator {
    var state: UInt64
    mutating func next() -> UInt64 {
        state &+= 0x9E3779B97F4A7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58476D1CE4E5B9
        z = (z ^ (z >> 27)) &* 0x94D049BB133111EB
        return z ^ (z >> 31)
    }
}

private func json(_ object: Any) -> String {
    String(data: try! JSONSerialization.data(withJSONObject: object), encoding: .utf8)!
}

