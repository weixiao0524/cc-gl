    func testBankValidationRejectsTampering() throws {
        let url = try XCTUnwrap(Bundle.module.url(forResource: "modeltrace_bank", withExtension: "json"))
        let original = try XCTUnwrap(JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        XCTAssertNoThrow(try ModelTraceBankLoader.decode(Data(contentsOf: url)))
        func mutated(_ change: (inout [String: Any]) -> Void) -> Data {
            var copy = original
            change(&copy)
            return try! JSONSerialization.data(withJSONObject: copy)
        }
        let tampered: [Data] = [
            mutated { $0["schema"] = "other" },
            mutated { var models = $0["models"] as! [[String: Any]]; models[0]["id"] = "bad id/../x"; $0["models"] = models },
            mutated { var models = $0["models"] as! [[String: Any]]; models[1]["counts"] = [1, 2, 3]; $0["models"] = models },
            mutated { var models = $0["models"] as! [[String: Any]]; models.removeLast(); $0["models"] = models },
            mutated { var calibration = $0["calibration"] as! [String: Any]; calibration.removeValue(forKey: "3"); $0["calibration"] = calibration },
            mutated { var robust = $0["robust"] as! [String: Any]; var h = robust["hellinger"] as! [String: Any]
                var mean = h["feature_mean"] as! [Double]; mean[3] = 0; mean.removeLast(); h["feature_mean"] = mean
                robust["hellinger"] = h; $0["robust"] = robust }
        ]
        for data in tampered { XCTAssertThrowsError(try ModelTraceBankLoader.decode(data)) }
        let overflow = String(data: mutated { _ in }, encoding: .utf8)!.replacingOccurrences(of: "\"beta\":", with: "\"beta\":1e999,\"x\":")
        XCTAssertThrowsError(try ModelTraceBankLoader.decode(Data(overflow.utf8)))
    }

    func testLoaderPrefersNewerValidCacheAndRefreshes() async throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let url = try XCTUnwrap(Bundle.module.url(forResource: "modeltrace_bank", withExtension: "json"))
        let source = try String(contentsOf: url, encoding: .utf8)
        let builtIn = try bank
        let builtAt = try XCTUnwrap(builtIn.built_at)
        let newer = source.replacingOccurrences(of: builtAt, with: "2099-01-01T00:00:00+00:00")

        let offline = ModelTraceBankLoader(cacheDirectory: directory, transport: ScriptedTransport { _, _ in .timeout })
        let (initial, source0) = try await offline.load()
        XCTAssertEqual(source0, .builtIn)
        let failed = await offline.refresh(newerThan: initial)
        XCTAssertNil(failed)

        let stale = ModelTraceBankLoader(cacheDirectory: directory, transport: ScriptedTransport { _, _ in .json(200, source) })
        let same = await stale.refresh(newerThan: initial)
        XCTAssertNil(same, "an equally old remote bank is not adopted")
        let broken = ModelTraceBankLoader(cacheDirectory: directory, transport: ScriptedTransport { _, _ in .json(200, "{\"schema\":1}") })
        let invalid = await broken.refresh(newerThan: initial)
        XCTAssertNil(invalid)

        let transport = ScriptedTransport { _, _ in .json(200, newer) }
        let online = ModelTraceBankLoader(cacheDirectory: directory, transport: transport)
        let refreshed = await online.refresh(newerThan: initial)
        XCTAssertEqual(refreshed?.built_at, "2099-01-01T00:00:00+00:00")
        let requests = await transport.requests
        XCTAssertEqual(requests.first?.url, ModelTraceBankLoader.remoteURL)
        let (cached, source1) = try await ModelTraceBankLoader(cacheDirectory: directory).load()
        XCTAssertEqual(source1, .cache)
        XCTAssertEqual(cached.built_at, "2099-01-01T00:00:00+00:00")

        // A corrupt cache falls back to the bundled bank instead of failing.
        try Data("garbage".utf8).write(to: directory.appendingPathComponent("modeltrace_bank.json"))
        let (fallback, source2) = try await ModelTraceBankLoader(cacheDirectory: directory).load()
        XCTAssertEqual(source2, .builtIn)
        XCTAssertEqual(fallback.built_at, builtAt)
    }

    func testChallengesAreDeterministicPerSeedAndUnique() {
        var a = SplitMix64(state: 42), b = SplitMix64(state: 42), c = SplitMix64(state: 43)
