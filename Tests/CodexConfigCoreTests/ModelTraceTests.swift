    func testRetriesAreBoundedAndBadAnswersDiscarded() async throws {
        // Every answer is truncated: each challenge is tried exactly twice, then given up.
        let truncated = ScriptedTransport { _, _ in .json(200, self.chat(self.answer(3), finish: "length")) }
        let collection = try await ModelTraceClient(transport: truncated).collect(ModelTraceChallenge.generate(), input: input) { _ in }
        let truncatedRequests = await truncated.requests
        XCTAssertEqual(truncatedRequests.count, 6)
        XCTAssertEqual(collection.failures["truncated"], 6)
        XCTAssertEqual(collection.outputs.map(\.text), ["", "", ""])
        XCTAssertThrowsError(try ModelTraceFingerprint.analyze(collection.outputs, bank: try bank))

        // Each challenge's first answer echoes the key, refuses or times out; the single retry succeeds.
        let good = answer(4)
        let challenges = ModelTraceChallenge.generate()
        let flaky = ScriptedTransport { request, repeats in
            guard repeats == 0 else { return .json(200, self.chat(good)) }
            let prompt = ((self.body(request)["messages"] as? [[String: Any]])?.first?["content"] as? String) ?? ""
            switch challenges.firstIndex(where: { $0.prompt == prompt }) {
            case 0: return .json(200, self.chat("Your key is dummy-test-key " + good))
            case 1: return .json(200, self.chat("抱歉，我不能生成随机数。"))
            default: return .timeout
            }
        }
        let recovered = try await ModelTraceClient(transport: flaky).collect(challenges, input: input) { _ in }
        let flakyRequests = await flaky.requests
        XCTAssertEqual(flakyRequests.count, 6)
        XCTAssertEqual(recovered.failures["credential_echo"], 1)
        XCTAssertEqual(recovered.failures["invalid_answer"], 1)
        XCTAssertEqual(recovered.failures["timeout"], 1)
        XCTAssertEqual(recovered.outputs.map(\.text), [good, good, good])
        XCTAssertFalse(recovered.outputs.contains { $0.text.contains("dummy-test-key") })
    }

    func testAuthFailureStopsWithoutEchoingBody() async throws {
        let transport = ScriptedTransport { _, _ in .json(401, "{\"error\":\"leaked dummy-test-key sk-upstream-secret\"}") }
        do {
            _ = try await ModelTraceClient(transport: transport).collect(ModelTraceChallenge.generate(), input: input) { _ in }
            XCTFail("expected auth failure")
        } catch {
            XCTAssertFalse(error.localizedDescription.contains("secret"))
            XCTAssertFalse(error.localizedDescription.contains("dummy-test-key"))
        }
        let requests = await transport.requests
        XCTAssertEqual(requests.count, 1)

        let unknown = ScriptedTransport { _, _ in .json(404, "<html>not found</html>") }
        do {
            _ = try await ModelTraceClient(transport: unknown).collect(ModelTraceChallenge.generate(), input: input) { _ in }
            XCTFail("expected format failure")
        } catch { XCTAssertFalse(error.localizedDescription.contains("html")) }
        let unknownRequests = await unknown.requests
        XCTAssertEqual(unknownRequests.count, 3, "each format probed once, nothing else sent")
    }

    func testCancellationStopsCollection() async throws {
        let transport = ScriptedTransport { _, _ in .timeout }
        let task = Task { try await ModelTraceClient(transport: transport).collect(ModelTraceChallenge.generate(), input: self.input) { _ in } }
        task.cancel()
        do { _ = try await task.value; XCTFail("expected cancellation") }
        catch { XCTAssertTrue(error is CancellationError) }
    }
